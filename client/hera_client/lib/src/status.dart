import 'package:flutter/foundation.dart';

import 'protocol.dart';
import 'transport.dart';

/// Connection state.
enum LinkPhase {
  /// The selected transport is not available on this platform.
  unsupported,

  /// Obtaining address and credentials: BLE scan and network join
  /// (`PROTOCOL.md` §3.5).
  provisioning,

  /// No device found; retrying.
  searching,

  connecting,

  /// The connection dropped and the session is being resumed (§5.4).
  resuming,

  connected,
}

/// Call state.
enum CallPhase { idle, ringing, active }

/// Link health over the last second.
///
/// `STATS` counters are cumulative; the values here are differences between
/// two consecutive frames (§13).
@immutable
class HeraHealth {
  const HeraHealth({
    this.downlink = 0,
    this.uplink = 0,
    this.uplinkSent = 0,
    this.audioPercent = 0,
    this.muted = false,
    this.dropped = 0,
    this.lost = 0,
    this.late = 0,
    this.fill = 0,
    this.bad = 0,
    this.bufferedMs = 0,
    this.jitterMs = 0,
    this.targetMs = 0,
    this.frameMs = 0,
    this.prebufferMs = 0,
    this.cpuPercent = 0,
    this.rssi = 0,
    this.protected = false,
  });

  /// Audio blocks per second received from and sent to the device, as
  /// counted by the device. They should be equal (§6.4).
  final int downlink;
  final int uplink;

  /// Blocks written by the client in the same second (§13.2).
  final int uplinkSent;

  /// Received downlink audio as a percentage of real time.
  final int audioPercent;

  /// True if `MUTE_UL` is active (§9).
  final bool muted;

  /// Blocks the device could not send (`dl_drop`, §6.6).
  final int dropped;

  /// Uplink blocks lost in the network (`ul_lost`).
  final int lost;

  /// Uplink blocks dropped at the jitter buffer ceiling (`ul_late`,
  /// §10.1).
  final int late;

  /// Silence generated by the device on underrun (`ul_fill`).
  final int fill;

  /// Malformed uplink blocks (`ul_bad`, §6.3).
  final int bad;

  /// Device uplink jitter buffer depth, in ms.
  final int bufferedMs;

  /// Uplink interarrival jitter measured by the device.
  final int jitterMs;

  /// Target depth of the device's adaptive jitter buffer (§6.5).
  final int targetMs;

  /// Negotiated block duration: 20, 10 or 5 ms (§6.2).
  final int frameMs;

  /// Audio buffered by the application before playback starts. Set by the
  /// application; not reported by the device.
  final int prebufferMs;

  final int cpuPercent;

  /// Client RSSI seen by the device, in dBm, or 0 if unknown.
  final int rssi;

  /// `STATS` flags bit 3: the underlying link is protected (WPA2 in AP mode,
  /// cable in USB mode). Diagnostic only; IP traffic is always encrypted
  /// (§11.1).
  final bool protected;

  /// True when there is no audio traffic.
  bool get isIdle => downlink == 0 && uplink == 0 && dropped == 0;

  /// True if any loss or drop counter is non-zero, or audio is below 95%.
  bool get isDegraded =>
      dropped > 0 || lost > 0 || late > 0 || bad > 0 || audioPercent < 95;

  bool get isHealthy => !isDegraded;

  @override
  String toString() => 'dl $downlink/s · ul $uplink/s (sent $uplinkSent) · '
      'audio $audioPercent% · lost $lost · late $late · drop $dropped · '
      'fill $fill · bad $bad · '
      'buffer $bufferedMs/${targetMs}ms · jitter ${jitterMs}ms · '
      'block ${frameMs}ms · prebuffer ${prebufferMs}ms · cpu $cpuPercent%'
      '${rssi == 0 ? '' : ' · rssi ${rssi}dBm'}';

  Map<String, Object?> toJson() => {
        'downlink': downlink,
        'uplink': uplink,
        'uplinkSent': uplinkSent,
        'audioPercent': audioPercent,
        'muted': muted,
        'dropped': dropped,
        'lost': lost,
        'late': late,
        'fill': fill,
        'bad': bad,
        'bufferedMs': bufferedMs,
        'jitterMs': jitterMs,
        'targetMs': targetMs,
        'frameMs': frameMs,
        'prebufferMs': prebufferMs,
        'cpuPercent': cpuPercent,
        'rssi': rssi,
        'protected': protected,
      };

  static HeraHealth fromJson(Map<String, Object?> json) => HeraHealth(
        downlink: (json['downlink'] as num?)?.toInt() ?? 0,
        uplink: (json['uplink'] as num?)?.toInt() ?? 0,
        uplinkSent: (json['uplinkSent'] as num?)?.toInt() ?? 0,
        audioPercent: (json['audioPercent'] as num?)?.toInt() ?? 0,
        muted: json['muted'] as bool? ?? false,
        dropped: (json['dropped'] as num?)?.toInt() ?? 0,
        lost: (json['lost'] as num?)?.toInt() ?? 0,
        late: (json['late'] as num?)?.toInt() ?? 0,
        fill: (json['fill'] as num?)?.toInt() ?? 0,
        bad: (json['bad'] as num?)?.toInt() ?? 0,
        bufferedMs: (json['bufferedMs'] as num?)?.toInt() ?? 0,
        jitterMs: (json['jitterMs'] as num?)?.toInt() ?? 0,
        targetMs: (json['targetMs'] as num?)?.toInt() ?? 0,
        frameMs: (json['frameMs'] as num?)?.toInt() ?? 0,
        prebufferMs: (json['prebufferMs'] as num?)?.toInt() ?? 0,
        cpuPercent: (json['cpuPercent'] as num?)?.toInt() ?? 0,
        rssi: (json['rssi'] as num?)?.toInt() ?? 0,
        protected: json['protected'] as bool? ?? false,
      );
}

/// Connection and call state for display.
///
/// Serialisable with [toJson] and [fromJson], so that it can cross isolate
/// boundaries.
@immutable
class HeraStatus {
  const HeraStatus({
    this.phase = LinkPhase.searching,
    this.call = CallPhase.idle,
    this.transport = HeraTransport.accessPoint,
    this.endpoint = '',
    this.format,
    this.caller,
    this.firmware,
    this.lastHeard,
    this.lastSaid,
    this.error,
    this.phoneConnected = false,
    this.audioOpen = false,
    this.health = const HeraHealth(),
  });

  final LinkPhase phase;
  final CallPhase call;
  final HeraTransport transport;

  /// Display form of the endpoint: `192.168.73.1:7420` or a serial port
  /// name.
  final String endpoint;

  /// Negotiated audio format (§6.2).
  final HeraFormat? format;

  /// Caller number, from `CLIP`.
  final String? caller;

  final String? firmware;

  /// Last recognised and last spoken text. Set by the application.
  final String? lastHeard;
  final String? lastSaid;

  final String? error;

  /// True if the phone is connected to the device (HFP SLC up).
  final bool phoneConnected;

  final bool audioOpen;
  final HeraHealth health;

  bool get isConnected => phase == LinkPhase.connected;

  /// True if a call is ringing or active.
  bool get isBusy => call != CallPhase.idle;

  /// True if the underlying link is protected (WPA2 or cable). Diagnostic
  /// only: IP traffic is encrypted in every mode (§11.1).
  bool get isProtected => transport.isProtected && health.protected;

  /// One-line summary, e.g. for a service notification.
  String get summary {
    if (error != null) return error!;
    return switch (phase) {
      LinkPhase.unsupported => 'Transport not available',
      LinkPhase.provisioning => 'Provisioning the device...',
      LinkPhase.searching => 'Waiting for the device...',
      LinkPhase.connecting => 'Connecting via ${transport.label}...',
      LinkPhase.resuming => 'Resuming the session...',
      LinkPhase.connected => switch (call) {
          CallPhase.idle => phoneConnected
              ? 'Ready, waiting for calls'
              : 'Waiting for the phone',
          CallPhase.ringing =>
            caller == null ? 'Ringing' : 'Call from $caller',
          CallPhase.active =>
            'In call${caller == null ? '' : ' with $caller'}',
        },
    };
  }

  HeraStatus copyWith({
    LinkPhase? phase,
    CallPhase? call,
    HeraTransport? transport,
    String? endpoint,
    HeraFormat? format,
    String? caller,
    String? firmware,
    String? lastHeard,
    String? lastSaid,
    String? error,
    bool? phoneConnected,
    bool? audioOpen,
    HeraHealth? health,
    bool clearCaller = false,
    bool clearError = false,
    bool clearFormat = false,
  }) =>
      HeraStatus(
        phase: phase ?? this.phase,
        call: call ?? this.call,
        transport: transport ?? this.transport,
        endpoint: endpoint ?? this.endpoint,
        format: clearFormat ? null : (format ?? this.format),
        caller: clearCaller ? null : (caller ?? this.caller),
        firmware: firmware ?? this.firmware,
        lastHeard: lastHeard ?? this.lastHeard,
        lastSaid: lastSaid ?? this.lastSaid,
        error: clearError ? null : (error ?? this.error),
        phoneConnected: phoneConnected ?? this.phoneConnected,
        audioOpen: audioOpen ?? this.audioOpen,
        health: health ?? this.health,
      );

  Map<String, Object?> toJson() => {
        'phase': phase.name,
        'call': call.name,
        'transport': transport.name,
        'endpoint': endpoint,
        if (format != null) 'format': format!.id,
        if (caller != null) 'caller': caller,
        if (firmware != null) 'firmware': firmware,
        if (lastHeard != null) 'lastHeard': lastHeard,
        if (lastSaid != null) 'lastSaid': lastSaid,
        if (error != null) 'error': error,
        'phoneConnected': phoneConnected,
        'audioOpen': audioOpen,
        'health': health.toJson(),
      };

  static HeraStatus fromJson(Map<String, Object?> json) => HeraStatus(
        phase: LinkPhase.values.firstWhere(
          (value) => value.name == json['phase'],
          orElse: () => LinkPhase.searching,
        ),
        call: CallPhase.values.firstWhere(
          (value) => value.name == json['call'],
          orElse: () => CallPhase.idle,
        ),
        transport: HeraTransport.values.firstWhere(
          (value) => value.name == json['transport'],
          orElse: () => HeraTransport.accessPoint,
        ),
        endpoint: json['endpoint'] as String? ?? '',
        format: HeraFormat.fromId((json['format'] as num?)?.toInt() ?? 0),
        caller: json['caller'] as String?,
        firmware: json['firmware'] as String?,
        lastHeard: json['lastHeard'] as String?,
        lastSaid: json['lastSaid'] as String?,
        error: json['error'] as String?,
        phoneConnected: json['phoneConnected'] as bool? ?? false,
        audioOpen: json['audioOpen'] as bool? ?? false,
        health: HeraHealth.fromJson(
          (json['health'] as Map?)?.cast<String, Object?>() ?? const {},
        ),
      );
}
